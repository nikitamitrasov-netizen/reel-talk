#!/usr/bin/env python
"""Merge content/films/*.json into js/data/films.js (window.FILM_DATA)."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "content" / "films"
OUT = ROOT / "js" / "data" / "films.js"
ORDER = ["A1", "A2", "B1", "B2", "C1", "C2"]


def main():
    films, seen = [], {}
    for path in sorted(SRC.glob("*.json")):
        if path.name.startswith("_"):
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        for film in data:
            fid = film["id"]
            if fid in seen:
                sys.exit(f"duplicate id {fid} in {path.name} and {seen[fid]}")
            seen[fid] = path.name
            film["_src"] = path.name
            poster = ROOT / "assets" / "posters" / (fid + ".jpg")
            if poster.exists() and poster.stat().st_size > 2000:
                film["poster"] = "assets/posters/" + fid + ".jpg"
            films.append(film)
    films.sort(key=lambda f: (ORDER.index(f["level"]), f["title"].lower()))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(films, ensure_ascii=False, indent=1)
    OUT.write_text(
        "/* generated by tools/build_data.py — edit content/films/*.json, then rebuild */\n"
        "window.FILM_DATA = " + payload + ";\n",
        encoding="utf-8",
    )
    counts = {lv: sum(1 for f in films if f["level"] == lv) for lv in ORDER}
    print(f"{len(films)} films -> {OUT.relative_to(ROOT)}")
    print("  " + "  ".join(f"{k}:{v}" for k, v in counts.items()))
    gaps = sum(len(f["gaps"]) for f in films)
    tasks = gaps + sum(len(f["quiz"]) + len(f["quotes"]) + len(f["quest"]) for f in films)
    print(f"  {sum(len(f['questions']) for f in films)} discussion questions, {tasks} interactive tasks, "
          f"{sum(len(f['scenes']) for f in films)} scene cues")


if __name__ == "__main__":
    main()
